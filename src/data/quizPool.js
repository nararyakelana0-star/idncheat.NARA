/** Kuis harian: 5 soal dari pool (3 asli + 3 pool), urutan acak per hari. */
export function dailyQuizForCourse(courseId, date = new Date()) {
  const quiz = QUIZZES[courseId]
  if (!quiz) return null
  const pool = [...quiz.questions, ...(QUIZ_POOL[courseId] || [])]
  const rand = mulberry32(daySeed(date) * 7919 + hashCode(courseId))
  // Fisher-Yates
  const arr = [...pool]
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j], arr[i]]
  }
  const picked = arr.slice(0, 5)
  // Essay selalu ada (jika pool memilikinya)
  const hasEssay = picked.some((q) => q.type === 'essay')
  const essayIdx = arr.findIndex((q) => q.type === 'essay')
  if (!hasEssay && essayIdx !== -1) picked[4] = arr[essayIdx]
  return {
    ...quiz,
    questions: picked,
    isDaily: true,
  }
}
